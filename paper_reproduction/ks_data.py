"""Generate complete KS physical datasets without reading saved arrays or weights.

The KS3D training initial cloud is generated by the retained Torch unit-ball
algorithm with seed 88, which matches all coordinates of the historical 15k
initial cloud. Its candidate historical Brownian recipe is a continuous NumPy
RandomState(88) stream across the eight conditions (32 normal draws). The first
15k training target was independently regenerated and matched bitwise; equality
of the remaining targets is verified separately. The original native evaluation
RNG sequence could not be recovered; this module explicitly uses fresh fixed
seeds 999+1009*i for each 10k source/reference pair. The 100k prediction source
uses that new 10k prefix and the original 90k suffix recipe. Its physical 100k
reference retains the recorded initialization/noise seeds 2026100902+sigma and
2026100903+sigma. No cached particles are embedded or copied into generation.

KS4D retains the documented shared unit-ball initial sources (train seed666,
native-evaluation seed999, 100k seed10999), with Brownian seeds base+1009*i.
All simulations use the retained float64 numerical kernels and float32 outputs.
The public prepare entry always generates 8x15k training, 20x10k native
evaluation, and 20x100k accuracy reference/source clouds per selected model.
"""
from __future__ import annotations

from contextlib import contextmanager
import hashlib
import json
from pathlib import Path
import time

from . import ROOT
from .experiments import _models, KS_MODELS
from .locations import fresh_directory

SEEDS = {"ks3d_train": 88, "native_eval": 999, "ks4d_train": 666,
         "ks3d_accuracy_source": 2026100901, "ks3d_accuracy_initial": 2026100902,
         "ks3d_accuracy_noise": 2026100903, "ks4d_accuracy": 10999}
LEVELS = tuple(range(10, 201, 10))
COUNTS = {"train": 15000, "eval": 10000, "reference": 100000}


def _sha(path):
    digest = hashlib.sha256()
    with Path(path).open("rb") as stream:
        for block in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(block)
    return digest.hexdigest()


def _json(path):
    return json.loads(Path(path).read_text(encoding="utf-8-sig"))


def _inside(root, value):
    root = Path(root).resolve(strict=True)
    path = (root / str(value).replace("\\", "/")).resolve(strict=True)
    if not path.is_relative_to(root):
        raise ValueError("KS data path escapes its prepared directory")
    return path


def _torch_ball(n, seed):
    import torch
    generator = torch.Generator(device="cpu").manual_seed(seed)
    radius = torch.rand(n, 1, generator=generator).pow(1 / 3)
    direction = torch.randn(n, 3, generator=generator)
    return (radius * direction / torch.linalg.vector_norm(direction, dim=1, keepdim=True)).numpy()


@contextmanager
def _legacy_noise(rng):
    import numpy as np
    previous = np.random.get_state()
    try:
        np.random.set_state(rng.get_state())
        yield
        rng.set_state(np.random.get_state())
    finally:
        np.random.set_state(previous)


def _simulate_3d(initial, level, protocol, rng, device):
    import torch
    from training.protocol import simulate_original
    with _legacy_noise(rng):
        return simulate_original(torch.from_numpy(initial), level, mu=protocol.mu, chi=protocol.chi,
            delta=protocol.delta, t=protocol.final_time, dt=protocol.dt, chunk=256, device=device).numpy()


def _recipes(name):
    if name == "ks3d":
        return {"training_initial": "Torch CPU unit_ball, seed88, shared across eight conditions",
                "training_noise": "Continuous NumPy RandomState(88), 4 full (15000,3) normal draws per condition",
                "native_eval": "Independent Torch unit_ball and NumPy RandomState, both seed999+1009*i",
                "accuracy_reference": "Torch unit_ball seed2026100902+sigma; NumPy RandomState seed2026100903+sigma",
                "accuracy_source": "New native-eval source prefix + 90000 Torch unit_ball points seed2026100901+sigma",
                "historical_initial_identity": "15000-point initial cloud verified bitwise from seed88",
                "historical_target_identity": "First 15000-point target verified bitwise; other seven conditions require independent comparison",
                "native_eval_difference": "Original RNG sequence unavailable; explicit new fixed-seed realization"}
    return {"training_initial": "NumPy default_rng(666) uniform 4D unit ball, shared across conditions",
            "training_noise": "NumPy default_rng(666+1009*i)",
            "native_eval": "Shared NumPy default_rng(999) unit ball; noise default_rng(999+1009*i)",
            "accuracy_reference": "Shared NumPy default_rng(10999) unit ball; noise default_rng(10999+1009*i)",
            "accuracy_source": "Same shared 100000-point unit-ball initial array",
            "historical_target_identity": "Recorded protocol retained; equality verified separately"}


def _prepare(models, destination, *, device, counts, purpose):
    """Internal parameterization permits a labelled CPU test, never paper claims."""
    import numpy as np
    import torch
    from dataclasses import replace
    from particle_pipeline.data import write_json, write_npz
    from particle_pipeline.physics import ks_simulate, unit_ball
    from particle_pipeline.protocol import fingerprint, preset
    from training.protocol import sigma_grid
    selected = _models(models, KS_MODELS)
    destination = fresh_directory(destination, create=True)
    if device == "cuda" and not torch.cuda.is_available():
        raise RuntimeError("Full KS physical data preparation requires CUDA")
    torch.set_num_threads(1)
    torch.backends.cuda.matmul.allow_tf32 = False
    torch.backends.cudnn.allow_tf32 = False
    torch.use_deterministic_algorithms(True)
    sources = [Path(__file__), ROOT / "deepparticle/training/protocol.py", ROOT / "deepparticle/training/core.py",
               ROOT / "deepparticle/particle_pipeline/physics.py", ROOT / "deepparticle/particle_pipeline/protocol.py"]
    generator = {path.relative_to(ROOT).as_posix(): _sha(path) for path in sources}
    result = {"schema": "ks_physical_data_v1", "status": "running", "purpose": purpose,
              "models": selected, "counts": counts, "levels": list(LEVELS), "seeds": SEEDS,
              "generator_sha256": generator, "datasets": {}, "reference_files": {},
              "saved_arrays_or_weights_read": False, "device": device,
              "numpy": np.__version__, "torch": str(torch.__version__)}
    write_json(destination / "manifest.json", result)
    started = time.perf_counter()
    for name in selected:
        p = replace(preset(name), n_train=counts["train"], n_eval=counts["eval"])
        train_levels = [float(value) for value in sigma_grid()] if name == "ks3d" else p.train_levels
        identity = {"schema": "ks_generated_training_v1", "protocol": p.metadata(), "recipes": _recipes(name),
                    "train_levels": train_levels, "eval_levels": list(LEVELS), "generator_sha256": generator,
                    "purpose": purpose, "backend": {"device": device, "numpy": np.__version__, "torch": str(torch.__version__)}}
        manifest = {**identity, "signature": fingerprint(identity), "status": "preparing", "train": [], "eval": []}
        folder = destination / "datasets" / name
        write_json(folder / "manifest.json", manifest)
        train_source = (_torch_ball(counts["train"], 88) if name == "ks3d" else
                        unit_ball(counts["train"], 4, np.random.default_rng(666)).astype(np.float32))
        train_noise = np.random.RandomState(88)
        native_sources = []
        for split, levels, count in (("train", train_levels, counts["train"]), ("eval", LEVELS, counts["eval"])):
            for index, level in enumerate(levels):
                seed = (666 if split == "train" else 999) + 1009 * index
                if split == "train":
                    initial = train_source
                elif name == "ks3d":
                    initial = _torch_ball(count, seed)
                else:
                    initial = unit_ball(count, 4, np.random.default_rng(999)).astype(np.float32)
                if name == "ks3d":
                    rng = train_noise if split == "train" else np.random.RandomState(seed)
                    target = _simulate_3d(initial, level, p, rng, device)
                else:
                    target = ks_simulate(initial, level, p, seed=seed, chunk=256, device=device)["target"]
                path = folder / "clouds" / f"{split}_{index:02d}.npz"
                meta = {"protocol": p.metadata(), "dataset_signature": manifest["signature"], "split": split,
                        "index": index, "level": level, "particles": count, "recipes": _recipes(name),
                        "noise_seed": 88 if name == "ks3d" and split == "train" else seed,
                        "continuous_noise_step_offset": 4 * index if name == "ks3d" and split == "train" else 0}
                write_npz(path, meta=meta, initial=initial, prior=initial, target=target)
                manifest[split].append({"level": float(level), "parameter": float(level),
                                        "file": path.relative_to(folder).as_posix(), "sha256": _sha(path)})
                if split == "eval":
                    native_sources.append(initial.copy())
                write_json(folder / "manifest.json", manifest)
                print(f"PHYSICS {name} {split} sigma={level:g}: {count} particles", flush=True)
        manifest["status"] = "complete"
        write_json(folder / "manifest.json", manifest)
        result["datasets"][name] = {"path": folder.relative_to(destination).as_posix(),
            "manifest_sha256": _sha(folder / "manifest.json"), "signature": manifest["signature"], "protocol": p.metadata()}
        result["reference_files"][name] = []
        for index, level in enumerate(LEVELS):
            count = counts["reference"]
            if name == "ks3d":
                initial_seed, noise_seed = SEEDS["ks3d_accuracy_initial"] + level, SEEDS["ks3d_accuracy_noise"] + level
                initial = _torch_ball(count, initial_seed)
                target = _simulate_3d(initial, level, p, np.random.RandomState(noise_seed), device)
                prefix = native_sources[index]
                source = np.concatenate((prefix, _torch_ball(count - len(prefix), SEEDS["ks3d_accuracy_source"] + level)))
            else:
                initial_seed, noise_seed = 10999, 10999 + 1009 * index
                initial = unit_ball(count, 4, np.random.default_rng(initial_seed)).astype(np.float32)
                target = ks_simulate(initial, level, p, seed=noise_seed, chunk=256, device=device)["target"]
                source = initial.copy()
            path = destination / "references" / name / f"sigma{level}.npz"
            meta = {"model": name, "sigma": level, "particles": count, "protocol": p.metadata(),
                    "dataset_signature": manifest["signature"], "initial_seed": initial_seed, "noise_seed": noise_seed,
                    "recipes": _recipes(name), "physical_simulation_executed": True}
            write_npz(path, meta=meta, source=source, reference_initial=initial, reference=target)
            result["reference_files"][name].append({"sigma": level, "file": path.relative_to(destination).as_posix(),
                                                    "sha256": _sha(path), **meta})
            write_json(destination / "manifest.json", result)
            print(f"PHYSICS {name} accuracy sigma={level}: {count} interacting reference particles", flush=True)
    result.update(status="complete", elapsed_seconds=time.perf_counter() - started)
    write_json(destination / "manifest.json", result)
    return result


def prepare(models: list[str], destination: Path) -> dict:
    """Generate the complete paper-size data from fixed RNGs; no input data needed."""
    return _prepare(models, destination, device="cuda", counts=dict(COUNTS), purpose="paper")


def _manifest(data_run, name):
    root = Path(data_run).expanduser().resolve(strict=True)
    manifest = _json(root / "manifest.json")
    if (manifest.get("schema") != "ks_physical_data_v1" or manifest.get("status") != "complete"
            or manifest.get("purpose") != "paper" or manifest.get("counts") != COUNTS
            or manifest.get("levels") != list(LEVELS) or name not in manifest.get("models", [])):
        raise ValueError("Expected a completed full-size KS physical-data preparation containing this model")
    return root, manifest


def dataset_identity(name: str, data_run: Path):
    """Return (dataset_folder, Protocol, manifest), validating the new identity."""
    from particle_pipeline.protocol import Protocol, fingerprint
    root, prepared = _manifest(data_run, name)
    record = prepared["datasets"][name]
    folder = _inside(root, record["path"])
    path = _inside(folder, "manifest.json")
    manifest = _json(path)
    identity = {key: value for key, value in manifest.items() if key not in ("signature", "status", "train", "eval")}
    if (_sha(path) != record["manifest_sha256"] or manifest.get("status") != "complete"
            or manifest["signature"] != record["signature"] or manifest["signature"] != fingerprint(identity)
            or manifest["protocol"] != record["protocol"] or len(manifest["train"]) != 8 or len(manifest["eval"]) != 20):
        raise ValueError("Prepared KS dataset manifest identity or coverage mismatch")
    fields = Protocol.__dataclass_fields__
    protocol = Protocol(**{key: manifest["protocol"][key] for key in fields})
    if protocol.metadata() != manifest["protocol"] or protocol.name != name or protocol.n_train != 15000 or protocol.n_eval != 10000:
        raise ValueError("Prepared KS dataset has a different physical protocol")
    return folder, protocol, manifest


def load_dataset(name: str, data_run: Path):
    """Return (folder, protocol, manifest, splits) for the shared training loader."""
    from particle_pipeline.data import load_dataset as load
    folder, expected, manifest = dataset_identity(name, data_run)
    protocol, loaded, splits = load(folder)
    if protocol.metadata() != expected.metadata() or loaded["signature"] != manifest["signature"]:
        raise ValueError("Prepared dataset loader returned another identity")
    for split, count in (("train", 15000), ("eval", 10000)):
        for case in splits[split]:
            if any(case[key].shape != (count, protocol.dimension) for key in ("initial", "prior", "target")):
                raise ValueError("Prepared KS dataset has a wrong particle count")
    return folder, protocol, loaded, splits


def reference_inputs(name: str, level: int, data_run: Path):
    """Return (NPZ path, manifest record) for a verified new 100k reference/source."""
    root, manifest = _manifest(data_run, name)
    records = manifest["reference_files"][name]
    if len(records) != 20 or {record["sigma"] for record in records} != set(LEVELS):
        raise ValueError("Prepared KS accuracy references do not cover all twenty amplitudes")
    record = next((record for record in records if record["sigma"] == level), None)
    if record is None:
        raise ValueError(f"KS amplitude absent from prepared references: {level}")
    path = _inside(root, record["file"])
    if _sha(path) != record["sha256"] or record["particles"] != 100000:
        raise ValueError("Prepared KS reference hash or particle count mismatch")
    return path, record
